/**
 * The backend validates CMS blocks against backend/apps/content/block_manifest.json,
 * generated from this registry (docs/CMS-COMPLETION-PLAN.md). This test fails
 * when the two drift. Regenerate with:
 *
 *   UPDATE_CMS_MANIFEST=1 npx vitest run src/cms/manifest.test.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { describe, expect, it } from 'vitest';
import { BLOCKS, type BlockSpec, type FieldKind, type FieldSpec } from './blocks/registry';
import { allSections, allTemplates, sectionSpec } from './sections';
import { loadAllGroups } from './sections/loaders';
import { templateBlocks } from './sections/types';
import { CURRENT_CYCLE, ROUTE_META, SCHOOL_YEARS } from '@/lib/siteMeta';

const MANIFEST = resolve(process.cwd(), '../backend/apps/content/block_manifest.json');
const TEMPLATE_MANIFEST = resolve(process.cwd(), '../backend/apps/content/template_manifest.json');

const PY_KIND: Record<FieldKind, string> = {
  text: 'str', textarea: 'str', richtext: 'str', url: 'str', select: 'str', icon: 'str', color: 'str',
  image: 'image', images: 'list', items: 'list', link: 'dict', toggle: 'bool', number: 'num',
  href: 'str', form: 'str', table: 'dict', action: 'str',
};

function imagePaths(fields: FieldSpec[], prefix = ''): string[] {
  return fields.flatMap((fs) => {
    if (fs.kind === 'image') return [`${prefix}${fs.key}`];
    if (fs.kind === 'images') return [`${prefix}${fs.key}[].image`];
    if (fs.kind === 'items') return imagePaths(fs.item ?? [], `${prefix}${fs.key}[].`);
    return [];
  });
}

/** Spanish label of every field path (`items[].title`): the backend names fields in its errors with these, never with keys. */
function fieldLabels(fields: FieldSpec[], prefix = ''): [string, string][] {
  return fields.flatMap((fs): [string, string][] => [
    [`${prefix}${fs.key}`, fs.label],
    ...(fs.kind === 'items' ? fieldLabels(fs.item ?? [], `${prefix}${fs.key}[].`) : []),
  ]);
}

function entry(spec: BlockSpec) {
  // «Tabla» fields: the backend enforces their limits (content/table_block.py).
  const tables = Object.fromEntries(spec.fields.filter((fs) => fs.kind === 'table' && fs.limits).map((fs) => [fs.key, fs.limits]));
  return {
    label: spec.label,
    group: spec.group ?? '',
    locked: !!spec.locked,
    required: Object.fromEntries(spec.fields.filter((fs) => fs.required).map((fs) => [fs.key, PY_KIND[fs.kind]])),
    images: imagePaths(spec.fields),
    labels: Object.fromEntries(fieldLabels(spec.fields)),
    ...(Object.keys(tables).length ? { tables } : {}),
  };
}

async function build() {
  await loadAllGroups();
  const specs = [...BLOCKS, ...allSections()].sort((a, b) => a.type.localeCompare(b.type));
  return {
    _comment: 'Generated by frontend/src/cms/manifest.test.ts; do not edit. UPDATE_CMS_MANIFEST=1 npx vitest run src/cms/manifest.test.ts',
    types: Object.fromEntries(specs.map((s) => [s.type, entry(s)])),
  };
}

/** Years that roll over on 1 January become tokens the backend expands (apps/content/page_templates.py). */
const tokenize = (s: string) => s.split(CURRENT_CYCLE).join('{{ciclo}}').split(`${SCHOOL_YEARS} años`).join('{{anios}} años');

/**
 * The public pages that render a designed template, with the SEO the site shows
 * when the CMS sets none (the template's own, else the route defaults of
 * RouteSeo). The backend uses it to tell designed pages from custom ones, to
 * write that SEO into the server-rendered <head> and to skip false SEO warnings.
 */
async function buildTemplates() {
  await loadAllGroups();
  const templates = [...allTemplates()].sort((a, b) => a.slug.localeCompare(b.slug));
  return {
    _comment: 'Generated by frontend/src/cms/manifest.test.ts; do not edit. UPDATE_CMS_MANIFEST=1 npx vitest run src/cms/manifest.test.ts',
    templates: Object.fromEntries(templates.map((t) => {
      const route = ROUTE_META[t.path];
      return [t.slug, {
        path: t.path,
        title: t.title,
        seo: { title: tokenize(t.seo.title ?? route?.title ?? ''), description: tokenize(t.seo.description ?? route?.description ?? '') },
      }];
    })),
  };
}

// Loading every section module cold is slow on a busy CI runner.
const LOAD_TIMEOUT = 30_000;

describe('CMS block manifest', () => {
  it('matches backend/apps/content/block_manifest.json', async () => {
    const built = await build();
    const text = `${JSON.stringify(built, null, 2)}\n`;
    if (process.env.UPDATE_CMS_MANIFEST) writeFileSync(MANIFEST, text, 'utf-8');
    expect(readFileSync(MANIFEST, 'utf-8').replace(/\r\n/g, '\n')).toBe(text);
  }, LOAD_TIMEOUT);

  it('matches backend/apps/content/template_manifest.json', async () => {
    const built = await buildTemplates();
    const text = `${JSON.stringify(built, null, 2)}\n`;
    if (process.env.UPDATE_CMS_MANIFEST) writeFileSync(TEMPLATE_MANIFEST, text, 'utf-8');
    expect(readFileSync(TEMPLATE_MANIFEST, 'utf-8').replace(/\r\n/g, '\n')).toBe(text);
  }, LOAD_TIMEOUT);

  it('every template renders only registered types, with its required props filled', async () => {
    await loadAllGroups();
    const templates = allTemplates();
    // 18 public pages (the calendar page left the site, owner 2026-11-08).
    expect(templates.length).toBeGreaterThanOrEqual(18);
    const slugs = new Set<string>();
    for (const t of templates) {
      expect(slugs.has(t.slug), `duplicate slug ${t.slug}`).toBe(false);
      slugs.add(t.slug);
      for (const b of templateBlocks(t, sectionSpec)) {
        const spec = sectionSpec(b.type) ?? BLOCKS.find((g) => g.type === b.type);
        expect(spec, `${t.slug}: unknown type ${b.type}`).toBeTruthy();
        for (const fs of spec!.fields.filter((x) => x.required)) {
          const v = b.props[fs.key];
          expect(v !== undefined && v !== '' && !(Array.isArray(v) && v.length === 0), `${t.slug} ${b.type}: "${fs.key}" empty`).toBe(true);
        }
      }
    }
  }, LOAD_TIMEOUT);

  it('section defaults only reference existing site photos or library ids', async () => {
    await loadAllGroups();
    const { existsSync } = await import('node:fs');
    const missing: string[] = [];
    const walk = (v: unknown) => {
      if (typeof v === 'string' && /^\/assets\/.+\.(webp|png|jpe?g|svg)$/.test(v) && !existsSync(resolve(process.cwd(), 'public', `.${v}`))) missing.push(v);
      else if (Array.isArray(v)) v.forEach(walk);
      else if (v && typeof v === 'object') Object.values(v).forEach(walk);
    };
    allSections().forEach((s) => walk(s.defaults));
    allTemplates().forEach((t) => t.sections.forEach((e) => typeof e !== 'string' && walk(e.props)));
    expect(missing).toEqual([]);
  }, LOAD_TIMEOUT);
});
